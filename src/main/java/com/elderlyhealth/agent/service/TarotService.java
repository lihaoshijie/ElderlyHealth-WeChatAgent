    private static final String[] SUIT_NAMES = {"权杖", "圣杯", "宝剑", "星币"};
    private static final List<String[][]> SUITS = List.of(WANDS, CUPS, SWORDS, PENTACLES);

    public String draw(String spreadType) {
        List<Card> deck = buildDeck();
        Collections.shuffle(deck, new Random());

        switch (spreadType != null ? spreadType : "three") {
            case "single": return formatSingle(deck);
            case "cross": return formatCross(deck);
            default: return formatThree(deck);
        }
    }

    private List<Card> buildDeck() {
        List<Card> deck = new ArrayList<>();
        for (int i = 0; i < MAJOR.length; i++) {
            deck.add(new Card(MAJOR[i][0], MAJOR[i][1], MAJOR[i][2]));
        }
        for (String[][] suit : SUITS) {
            for (int i = 0; i < suit.length; i++) {
                deck.add(new Card(suit[i][0], suit[i][1], suit[i][2]));
            }
        }
        return deck;
    }

    private String formatSingle(List<Card> deck) {
        Card c = deck.get(0);
        boolean upright = new Random().nextBoolean();
        return "【塔罗占卜 - 单张指引】\n\n"
             + "抽到：" + c.name + "（" + (upright ? "正位" : "逆位") + "）\n"
             + "含义：" + (upright ? c.upright : c.reversed) + "\n\n"
             + "— 以上为牌面信息，请结合用户问题给出解读 —";
    }

    private String formatThree(List<Card> deck) {
        String[] positions = {"过去", "现在", "未来"};
        StringBuilder sb = new StringBuilder("【塔罗占卜 - 三张牌阵】\n\n");
        for (int i = 0; i < 3; i++) {
            Card c = deck.get(i);
            boolean upright = new Random().nextBoolean();
            sb.append(positions[i]).append("：").append(c.name)
              .append("（").append(upright ? "正位" : "逆位").append("）\n")
              .append("  → ").append(upright ? c.upright : c.reversed).append("\n\n");
        }
        sb.append("— 以上为牌面信息，请结合用户问题给出解读 —");
        return sb.toString();
    }

    private String formatCross(List<Card> deck) {
        String[] positions = {"问题核心", "当前阻碍", "过去根源", "发展趋势", "最终结果"};
        StringBuilder sb = new StringBuilder("【塔罗占卜 - 十字牌阵】\n\n");
        for (int i = 0; i < 5; i++) {
            Card c = deck.get(i);
            boolean upright = new Random().nextBoolean();
            sb.append(positions[i]).append("：").append(c.name)
              .append("（").append(upright ? "正位" : "逆位").append("）\n")
              .append("  → ").append(upright ? c.upright : c.reversed).append("\n\n");
        }
        sb.append("— 以上为牌面信息，请结合用户问题给出解读 —");
        return sb.toString();
    }

    public String[] getSpreadTypes() {
        return new String[]{"single", "three", "cross"};
    }

    private static class Card {
        final String name;
        final String upright;
        final String reversed;

        Card(String name, String upright, String reversed) {
            this.name = name;
            this.upright = upright;
            this.reversed = reversed;
        }
    }
